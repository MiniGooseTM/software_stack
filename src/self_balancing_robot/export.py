"""Export the trained actor's weights for the ESP32 (ARCHITECTURE.md, section 4).

Two files with the same content:
- a C header with every actor layer as ``W[out][in]`` / ``b[out]`` (y = W x + b, ReLU on all
  layers but the last) and the constants needed to build the observation exactly as in
  training (scaling, history length, control period, limits);
- a binary policy file, which the robot firmware embeds as its built-in policy (and which can
  be uploaded through its web page). It also holds test vectors, the trained policy's own
  actions (Brax, in JAX) for a few simulated observations, that the firmware checks its
  forward pass against at boot.

Policy file, version 1, little-endian (read by ESP32_software/robot/main/policy_net.c):
    header (`_HEADER`, 96 bytes):
        magic b"GPOL", version, header size, total size (CRC included),
        layers, input size, output size, frame size, history length, test vectors,
        CRC-32 of the frame field names joined by ",",
        control period (s), max linear / angular command, half track (m),
        wheel no-load speed (rad/s), tilt limit (rad), model name (44 bytes, NUL-terminated)
    per layer: in, out, activation (0 none, 2 relu), reserved      4 x uint16
    per layer: W[out][in] row-major, then b[out]                     float32
    test inputs [tests][input size], test outputs [tests][output size]  float32
    CRC-32 (zlib) of everything before it                             uint32
"""

import argparse
import struct
import zlib
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
from brax.training.agents.ppo import networks as ppo_networks

from self_balancing_robot.actor import Actor, load_params, network_factory, resolve_model
from self_balancing_robot.curriculum import FULL_COMMAND
from self_balancing_robot.envs.balance_env import (
    ACTOR_FRAME_FIELDS,
    ACTOR_FRAME_SIZE,
    ACTOR_KEY,
    CRITIC_KEY,
    PRIVILEGED_SIZE,
    SelfBalancingRobotEnv,
)

DEFAULT_OUTPUT = Path("models/policy_weights.h")
DEFAULT_POLICY_FILE = Path("models/policy.bin")

POLICY_FILE_MAGIC = b"GPOL"
POLICY_FILE_VERSION = 1
_HEADER = struct.Struct("<4sHHIHHHHHHIffffff44s")
_LAYER = struct.Struct("<HHHH")
ACTIVATION_NONE = 0
ACTIVATION_RELU = 2
# Simulated observations (and the trained policy's actions) stored in the policy file for the
# boot self-test
NUM_TEST_VECTORS = 8

# Actor layers (W[out][in], b[out]); see `actor.Actor`.
Layers = list[tuple[np.ndarray, np.ndarray]]


def _floats(values) -> str:
    return ", ".join(f"{float(v):.9e}f" for v in np.ravel(values))


def _array(name: str, values: np.ndarray) -> str:
    dims = "".join(f"[{n}]" for n in values.shape)
    if values.ndim == 1:
        return f"static const float {name}{dims} = {{{_floats(values)}}};\n"
    rows = ",\n".join(f"    {{{_floats(row)}}}" for row in values)
    return f"static const float {name}{dims} = {{\n{rows}\n}};\n"


def _in(layer) -> int:
    return layer[0].shape[1]


def _out(layer) -> int:
    return layer[0].shape[0]


def weights_header(model_path: Path, layers: Layers, env: SelfBalancingRobotEnv) -> str:
    sizes = [_in(layers[0]), *(_out(layer) for layer in layers)]
    command_limits = FULL_COMMAND
    lines = [
        "// Generated by `python -m self_balancing_robot.export` - do not edit.",
        f"// Model: {model_path.as_posix()}",
        f"// Actor: {' -> '.join(map(str, sizes))}, ReLU on all layers but the last;",
        "// clip the 2 outputs to [-1, 1] (0 = left, 1 = right duty). Row-major W[out][in]:",
        "// y = W x + b. See ARCHITECTURE.md, section 4.",
        "#pragma once",
        "",
        "// Observation (ARCHITECTURE.md 4.4): frames of POLICY_FRAME_SIZE values, newest first:",
        *(f"//   {i:2d} {name}" for i, name in enumerate(ACTOR_FRAME_FIELDS)),
        f"#define POLICY_FRAME_SIZE {ACTOR_FRAME_SIZE}",
        f"#define POLICY_HISTORY_LENGTH {env.history_length}",
        f"#define POLICY_INPUT_SIZE {_in(layers[0])}",
        f"#define POLICY_OUTPUT_SIZE {_out(layers[-1])}",
        f"#define POLICY_NUM_LAYERS {len(layers)}",
        f"#define POLICY_MAX_WIDTH {max(sizes)}",
        "",
        "// Training constants the firmware must match.",
        f"#define POLICY_CONTROL_PERIOD_S {env.dt:.6f}f",
        f"#define POLICY_MAX_LINEAR_COMMAND {command_limits[0]:.6f}f   // m/s",
        f"#define POLICY_MAX_ANGULAR_COMMAND {command_limits[1]:.6f}f  // rad/s",
        f"#define POLICY_HALF_TRACK_M {env.half_track:.6f}f",
        f"#define POLICY_WHEEL_NO_LOAD_SPEED {env.max_wheel_speed:.6f}f  // rad/s",
        f"#define POLICY_TILT_LIMIT_RAD {env.environment_config.upright_limit_radians:.6f}f",
        "",
    ]
    for i, (weight, bias) in enumerate(layers):
        lines.append(f"// Layer {i}: {weight.shape[1]} -> {weight.shape[0]}")
        lines.append(_array(f"POLICY_W{i}", weight))
        lines.append(_array(f"POLICY_B{i}", bias))
    weight_ptrs = ", ".join(f"&POLICY_W{i}[0][0]" for i in range(len(layers)))
    bias_ptrs = ", ".join(f"POLICY_B{i}" for i in range(len(layers)))
    lines += [
        f"static const float *const POLICY_WEIGHTS[POLICY_NUM_LAYERS] = {{{weight_ptrs}}};",
        f"static const float *const POLICY_BIASES[POLICY_NUM_LAYERS] = {{{bias_ptrs}}};",
        "static const int POLICY_LAYER_IN[POLICY_NUM_LAYERS] = {"
        + ", ".join(str(_in(layer)) for layer in layers)
        + "};",
        "static const int POLICY_LAYER_OUT[POLICY_NUM_LAYERS] = {"
        + ", ".join(str(_out(layer)) for layer in layers)
        + "};",
        "",
    ]
    return "\n".join(lines)


def frame_fields_crc() -> int:
    """Identifies the observation layout; the firmware hashes its own field list the same way."""
    return zlib.crc32(",".join(ACTOR_FRAME_FIELDS).encode())


def policy_file(
    model_path: Path,
    layers: Layers,
    env: SelfBalancingRobotEnv,
    test_inputs: np.ndarray,
    test_outputs: np.ndarray,
) -> bytes:
    command_limits = FULL_COMMAND
    name = model_path.as_posix().encode()[-43:]
    body = b"".join(
        _LAYER.pack(
            _in(layer),
            _out(layer),
            ACTIVATION_RELU if i < len(layers) - 1 else ACTIVATION_NONE,
            0,
        )
        for i, layer in enumerate(layers)
    )
    for weight, bias in layers:
        body += np.asarray(weight).astype("<f4").tobytes()
        body += np.asarray(bias).astype("<f4").tobytes()
    body += np.asarray(test_inputs, dtype="<f4").tobytes()
    body += np.asarray(test_outputs, dtype="<f4").tobytes()
    header = _HEADER.pack(
        POLICY_FILE_MAGIC,
        POLICY_FILE_VERSION,
        _HEADER.size,
        _HEADER.size + len(body) + 4,
        len(layers),
        _in(layers[0]),
        _out(layers[-1]),
        ACTOR_FRAME_SIZE,
        env.history_length,
        len(test_inputs),
        frame_fields_crc(),
        env.dt,
        command_limits[0],
        command_limits[1],
        env.half_track,
        env.max_wheel_speed,
        env.environment_config.upright_limit_radians,
        name,
    )
    data = header + body
    return data + struct.pack("<I", zlib.crc32(data))


def read_policy_file(data: bytes) -> dict:
    """Parse and check a policy file; the inverse of `policy_file`."""
    fields = _HEADER.unpack_from(data)
    (magic, version, header_size, total_size, num_layers, input_size, output_size) = fields[:7]
    if magic != POLICY_FILE_MAGIC or version != POLICY_FILE_VERSION or header_size != _HEADER.size:
        raise ValueError("not a version 1 policy file")
    if total_size != len(data):
        raise ValueError(f"file is {len(data)} bytes, header says {total_size}")
    (crc,) = struct.unpack_from("<I", data, total_size - 4)
    if zlib.crc32(data[: total_size - 4]) != crc:
        raise ValueError("CRC mismatch")
    names = (
        "frame_size",
        "history_length",
        "num_tests",
        "frame_fields_crc",
        "control_period_s",
        "max_linear_command",
        "max_angular_command",
        "half_track_m",
        "wheel_no_load_speed",
        "tilt_limit_rad",
    )
    policy = dict(zip(names, fields[7:17]))
    policy["name"] = fields[17].rstrip(b"\0").decode()
    offset = _HEADER.size
    shapes = [_LAYER.unpack_from(data, offset + i * _LAYER.size) for i in range(num_layers)]
    offset += num_layers * _LAYER.size

    def floats(count: int) -> np.ndarray:
        nonlocal offset
        values = np.frombuffer(data, dtype="<f4", count=count, offset=offset)
        offset += 4 * count
        return values

    policy["layers"] = [
        (floats(n_in * n_out).reshape(n_out, n_in), floats(n_out), activation)
        for n_in, n_out, activation, _ in shapes
    ]
    n = policy["num_tests"]
    policy["test_inputs"] = floats(n * input_size).reshape(n, input_size)
    policy["test_outputs"] = floats(n * output_size).reshape(n, output_size)
    if offset + 4 != total_size:
        raise ValueError("file size doesn't match its contents")
    return policy


def simulated_inputs(
    env: SelfBalancingRobotEnv, actor: Actor, seed: int, steps: int = 200
) -> np.ndarray:
    """Actor inputs from a closed-loop rollout of the policy at the env's (last) stage."""
    reset, step = jax.jit(env.reset), jax.jit(env.step)
    key = jax.random.PRNGKey(seed)
    state = reset(key)
    inputs = []
    for _ in range(steps):
        state = step(state, actor(state.obs))
        inputs.append(np.asarray(state.obs[ACTOR_KEY]))
        if state.done:
            key, reset_key = jax.random.split(key)
            state = reset(reset_key)
    return np.array(inputs, dtype=np.float32)


def reference_actions(model_path: Path, inputs: np.ndarray, actor: Actor) -> np.ndarray:
    """Clipped deterministic actions of the trained policy itself.

    For a training run these come from Brax's network (JAX), an implementation independent
    of the manual forward pass; a policy file only has its own weights to go by.
    """
    if model_path.suffix == ".bin":
        return actor.predict(inputs)
    params = load_params(model_path)
    networks = network_factory()(
        {ACTOR_KEY: (inputs.shape[1],), CRITIC_KEY: (PRIVILEGED_SIZE,)}, actor.sizes[-1]
    )
    policy = ppo_networks.make_inference_fn(networks)(params, deterministic=True)
    observations = {
        ACTOR_KEY: jnp.asarray(inputs),
        CRITIC_KEY: jnp.zeros((len(inputs), PRIVILEGED_SIZE)),
    }
    # Full float32 matmuls: on GPU, JAX defaults to TF32 (errors ~1e-4).
    with jax.default_matmul_precision("highest"):
        actions, _ = policy(observations, jax.random.PRNGKey(0))
    return np.clip(np.asarray(actions), -1.0, 1.0)


def export(
    model_path: Path, output: Path, seed: int = 0, policy_output: Path | None = None
) -> None:
    """Write the C header to `output` and the policy file to `policy_output` (by default
    next to it, as policy.bin). `model_path` is a training run (or its params.pkl)."""
    if policy_output is None:
        policy_output = output.with_name(DEFAULT_POLICY_FILE.name)
    actor = Actor.load(model_path)
    layers = actor.layers
    env = SelfBalancingRobotEnv(start_stage=-1)
    if actor.input_size != env.actor_observation_size:
        raise ValueError(
            f"{model_path} expects {actor.input_size} inputs, the environment builds "
            f"{env.actor_observation_size}"
        )
    inputs = simulated_inputs(env, actor, seed)
    expected = reference_actions(model_path, inputs, actor)
    # The firmware's forward pass (NumPy, float32) must reproduce the trained policy.
    np.testing.assert_allclose(actor.predict(inputs), expected, atol=1e-5)
    tests = np.linspace(0, len(inputs) - 1, NUM_TEST_VECTORS).astype(int)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(weights_header(model_path, layers, env))
    policy_output.parent.mkdir(parents=True, exist_ok=True)
    policy_output.write_bytes(
        policy_file(model_path, layers, env, inputs[tests], expected[tests])
    )
    print(
        f"Exported {model_path} ({' -> '.join(map(str, actor.sizes))}, "
        f"{actor.parameter_count:,} parameters, {actor.parameter_count * 4 / 1024:.0f} KB as "
        f"float32) to {output} and {policy_output}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export the actor weights to a C header and a policy file for the ESP32."
    )
    parser.add_argument(
        "--model", type=Path, default=None, help="Training run directory (default: the newest)."
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--policy-output",
        type=Path,
        default=None,
        help="Policy file for the robot firmware (default: policy.bin next to --output).",
    )
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    export(resolve_model(args.model), args.output, args.seed, args.policy_output)


if __name__ == "__main__":
    main()
