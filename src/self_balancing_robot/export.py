"""Export the trained actor's weights to a C header for the ESP32 (ARCHITECTURE.md, section 4).

The header holds every actor layer as ``W[out][in]`` / ``b[out]`` (y = W x + b, ReLU on all
layers but the last) and the constants needed to build the observation exactly as in
training (scaling, history length, control period, limits).
"""

import argparse
from pathlib import Path

import numpy as np
import torch

from self_balancing_robot.config import DEFAULT_TRAINING_CONFIG
from self_balancing_robot.envs.balance_env import (
    ACTOR_FRAME_FIELDS,
    ACTOR_FRAME_SIZE,
    SelfBalancingRobotEnv,
)
from self_balancing_robot.policy import load_model

DEFAULT_OUTPUT = Path("models/policy_weights.h")


def actor_layers(model) -> list[torch.nn.Linear]:
    """The actor's linear layers in order, ending with the 2-output action layer."""
    hidden = [m for m in model.policy.mlp_extractor.policy_net if isinstance(m, torch.nn.Linear)]
    return [*hidden, model.policy.action_net]


def actor_forward(layers: list[torch.nn.Linear], x: np.ndarray) -> np.ndarray:
    """Unclipped actor output for a batch of inputs, computed as the ESP32 does."""
    h = np.asarray(x, dtype=np.float32)
    for i, layer in enumerate(layers):
        h = h @ layer.weight.detach().numpy().T + layer.bias.detach().numpy()
        if i < len(layers) - 1:
            h = np.maximum(h, 0.0)
    return h


def _floats(values) -> str:
    return ", ".join(f"{float(v):.9e}f" for v in np.ravel(values))


def _array(name: str, values: np.ndarray) -> str:
    dims = "".join(f"[{n}]" for n in values.shape)
    if values.ndim == 1:
        return f"static const float {name}{dims} = {{{_floats(values)}}};\n"
    rows = ",\n".join(f"    {{{_floats(row)}}}" for row in values)
    return f"static const float {name}{dims} = {{\n{rows}\n}};\n"


def weights_header(model_path: Path, layers: list[torch.nn.Linear], env) -> str:
    sizes = [layers[0].in_features, *(layer.out_features for layer in layers)]
    command_limits = env.curriculum_config.command_limits
    lines = [
        "// Generated by `python -m self_balancing_robot.export` - do not edit.",
        f"// Model: {model_path.as_posix()}",
        f"// Actor: {' -> '.join(map(str, sizes))}, ReLU on all layers but the last;",
        "// clip the 2 outputs to [-1, 1] (0 = left, 1 = right duty). Row-major W[out][in]:",
        "// y = W x + b. See ARCHITECTURE.md, section 4.",
        "#pragma once",
        "",
        "// Observation (ARCHITECTURE.md 4.4): frames of POLICY_FRAME_SIZE values, newest first:",
        *(f"//   {i:2d} {name}" for i, name in enumerate(ACTOR_FRAME_FIELDS)),
        f"#define POLICY_FRAME_SIZE {ACTOR_FRAME_SIZE}",
        f"#define POLICY_HISTORY_LENGTH {env.history_length}",
        f"#define POLICY_INPUT_SIZE {layers[0].in_features}",
        f"#define POLICY_OUTPUT_SIZE {layers[-1].out_features}",
        f"#define POLICY_NUM_LAYERS {len(layers)}",
        f"#define POLICY_MAX_WIDTH {max(sizes)}",
        "",
        "// Training constants the firmware must match.",
        f"#define POLICY_CONTROL_PERIOD_S {env.dt:.6f}f",
        f"#define POLICY_MAX_LINEAR_COMMAND {command_limits[0]:.6f}f   // m/s",
        f"#define POLICY_MAX_ANGULAR_COMMAND {command_limits[1]:.6f}f  // rad/s",
        f"#define POLICY_HALF_TRACK_M {env._half_track:.6f}f",
        f"#define POLICY_WHEEL_NO_LOAD_SPEED {env._max_wheel_speed:.6f}f  // rad/s",
        f"#define POLICY_TILT_LIMIT_RAD {env.environment_config.upright_limit_radians:.6f}f",
        "",
    ]
    for i, layer in enumerate(layers):
        lines.append(f"// Layer {i}: {layer.in_features} -> {layer.out_features}")
        lines.append(_array(f"POLICY_W{i}", layer.weight.detach().numpy()))
        lines.append(_array(f"POLICY_B{i}", layer.bias.detach().numpy()))
    weight_ptrs = ", ".join(f"&POLICY_W{i}[0][0]" for i in range(len(layers)))
    bias_ptrs = ", ".join(f"POLICY_B{i}" for i in range(len(layers)))
    lines += [
        f"static const float *const POLICY_WEIGHTS[POLICY_NUM_LAYERS] = {{{weight_ptrs}}};",
        f"static const float *const POLICY_BIASES[POLICY_NUM_LAYERS] = {{{bias_ptrs}}};",
        "static const int POLICY_LAYER_IN[POLICY_NUM_LAYERS] = {"
        + ", ".join(str(layer.in_features) for layer in layers)
        + "};",
        "static const int POLICY_LAYER_OUT[POLICY_NUM_LAYERS] = {"
        + ", ".join(str(layer.out_features) for layer in layers)
        + "};",
        "",
    ]
    return "\n".join(lines)


def _check_forward(model, layers: list[torch.nn.Linear], env, seed: int) -> None:
    """The manual forward pass must reproduce SB3's action on simulated inputs."""
    observation, _ = env.reset(seed=seed)
    observations = []
    for _ in range(200):
        action, _ = model.predict(observation, deterministic=True)
        observation, _, terminated, truncated, _ = env.step(action)
        observations.append(observation)
        if terminated or truncated:
            observation, _ = env.reset()
    observations = np.array(observations, dtype=np.float32)
    expected, _ = model.predict(observations, deterministic=True)
    manual = actor_forward(layers, observations[:, : env.actor_observation_size])
    np.testing.assert_allclose(np.clip(manual, -1.0, 1.0), expected, atol=1e-5)


def export(model_path: Path, output: Path, seed: int = 0) -> None:
    model = load_model(model_path, device="cpu")
    layers = actor_layers(model)
    env = SelfBalancingRobotEnv(curriculum_stage=3)
    env.set_difficulty_level(env.max_level)
    if layers[0].in_features != env.actor_observation_size:
        raise ValueError(
            f"{model_path} expects {layers[0].in_features} inputs, the environment builds "
            f"{env.actor_observation_size}"
        )
    _check_forward(model, layers, env, seed)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(weights_header(model_path, layers, env))
    env.close()
    sizes = [layers[0].in_features, *(layer.out_features for layer in layers)]
    parameters = sum(layer.weight.numel() + layer.bias.numel() for layer in layers)
    print(
        f"Exported {model_path} ({' -> '.join(map(str, sizes))}, {parameters:,} parameters, "
        f"{parameters * 4 / 1024:.0f} KB as float32) to {output}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Export the actor weights to a C header.")
    parser.add_argument("--model", type=Path, default=DEFAULT_TRAINING_CONFIG.evaluation_model_path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    export(args.model, args.output, args.seed)


if __name__ == "__main__":
    main()
